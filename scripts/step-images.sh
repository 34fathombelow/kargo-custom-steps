#!/usr/bin/env bash
# Regenerates the "Image" section of every step README from the Dockerfile of
# the image the step uses, so readers see exactly what the step runs in.
# make lint fails when a README is out of date (e.g. after a Renovate bump).
#
#   scripts/step-images.sh              # every step
#   scripts/step-images.sh trivy-image  # one step
set -euo pipefail
trap 'echo "step-images.sh: unexpected error on line $LINENO" >&2' ERR
cd "$(git rev-parse --show-toplevel)"

section() { # section <tool> <image>: the generated Markdown
  local tool="$1" image="$2"
  echo "<!-- step-image:start (generated by scripts/step-images.sh from docker/$tool/Dockerfile; do not edit by hand) -->"
  echo "## Image"
  echo
  echo "\`$image\`, built from [\`docker/$tool/Dockerfile\`](../../../../docker/$tool/Dockerfile) and published by this repo's"
  echo "GitHub Actions:"
  echo
  echo '```dockerfile'
  cat "docker/$tool/Dockerfile"
  echo '```'
  echo "<!-- step-image:end -->"
}

steps=("$@")
if [ ${#steps[@]} -eq 0 ]; then
  for f in kargo/custom-steps/*/*/*.yaml; do steps+=("$(basename "$f" .yaml)"); done
fi
for step in "${steps[@]}"; do
  def="$(ls kargo/custom-steps/*/"$step"/"$step".yaml 2>/dev/null)" || { echo "step-images.sh: no step named $step" >&2; exit 1; }
  readme="$(dirname "$def")/README.md"
  image="$(sed -nE 's/^  image: *//p' "$def" | head -1 || true)"
  tool="$(sed -nE 's#^[^/]+/[^/]+/([^:@]+).*#\1#p' <<<"$image")"
  [ -f "docker/$tool/Dockerfile" ] || { echo "step-images.sh: $def uses $image, but docker/$tool/Dockerfile doesn't exist" >&2; exit 1; }
  tmp="$(mktemp)"; section "$tool" "$image" > "$tmp"
  SECTION="$tmp" perl -0pi -e '
    my $new = do { local $/; open my $f, "<", $ENV{SECTION} or die; <$f> };
    if (/<!-- step-image:start.*?<!-- step-image:end -->\n/s) {
      s/<!-- step-image:start.*?<!-- step-image:end -->\n/$new/s;
    } elsif (/\n## Config\n/) {
      s/\n## Config\n/\n$new\n## Config\n/;
    } else {
      $_ .= "\n$new";
    }' "$readme"
  rm -f "$tmp"
  echo "updated $readme"
done
