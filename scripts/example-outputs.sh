#!/usr/bin/env bash
# Regenerates the "Example output" section of every step README from real
# harness runs, so the examples always match what the step actually records on
# a promotion. Needs the step images built locally (make images) and network
# access for the steps that pull images or git repositories.
#
#   scripts/example-outputs.sh              # every step
#   scripts/example-outputs.sh trivy-image  # one step
set -euo pipefail
trap 'echo "example-outputs.sh: unexpected error on line $LINENO" >&2' ERR
cd "$(git rev-parse --show-toplevel)"

# step -> "<label>:<fixture> <label>:<fixture>" (shown in this order).
declare -A runs=(
  [kyverno-apply]="Passes:compliant Blocked:violating"
  [opa-conftest]="Passes:compliant Blocked:violating"
  [opa-promotion-gate]="Allowed:prod-allowed Denied:prod-denied"
  [trivy-image]="Passes:pass Blocked:blocked"
  [cosign-verify]="Verified:verified Blocked:unsigned"
  [slsa-verify]="Verified:verified Blocked:wrong-tag"
  [deprecated-apis]="Passes:k8s-1-25-passes Blocked:k8s-1-33-blocked"
  [cluster-version]="Found:01-single-cluster Ambiguous:03-ambiguous"
  [manifest-diff]="Changed:changed-dirs Unchanged:unchanged"
  [release-diff]="Forward:forward Rollback:rollback"
  [argocd-drift-check]="Passes:synced-healthy Blocked:out-of-sync"
  [sentry-release]="Recorded:new-release Failed:unknown-project"
  [flyway-migrate]="Migrates:01-migrate Rollback:03-rollback"
  [jsonnet-render]="Renders:render-dir"
  [cdk8s-synth]="Renders:render Blocked:type-error"
  [cdk8s-synth-python]="Renders:render Blocked:type-error"
  [cdk8s-synth-go]="Renders:render Blocked:type-error"
)
# flyway-migrate's fixtures share a database and run in order: a fresh test
# database is started first, then 01 (migrate) and 03 (rollback of the same DB).

# Keep examples readable: at most 3 items per list, long strings cut.
trim='def t: if type == "array" and length > 3 then .[:3] + ["… \(length - 3) more"]
             elif type == "string" and length > 300 then .[:300] + "…" else . end;
      walk(t)'

run() { # run <step> <fixture>: prints harness output (status line, JSON, MESSAGE line)
  local step="$1" fixture="$2" file
  file="$(ls kargo/custom-steps/*/"$step"/"$step".yaml)"
  go -C test run ./cmd/runstep -message -repo "$PWD" -step "$PWD/$file" -fixture "$PWD/test/fixtures/$step/$fixture.yaml" || true
}

section() { # section <step>: prints the generated markdown section
  local step="$1" pair label fixture out json message desc status
  echo "<!-- example-output:start (generated by scripts/example-outputs.sh; do not edit by hand) -->"
  echo "## Example output"
  echo
  echo "Real output from the [test fixtures](../../../../test/fixtures/$step), run with the local harness. A promotion shows"
  echo "the same output in the Kargo UI. Long lists and strings are trimmed here."
  for pair in ${runs[$step]}; do
    label="${pair%%:*}"; fixture="${pair#*:}"
    out="$(run "$step" "$fixture")"
    status="$(head -1 <<<"$out" | cut -d' ' -f1)"
    desc="$(yq '.description' "test/fixtures/$step/$fixture.yaml")"
    json="$(sed -n '2,/^MESSAGE: /p' <<<"$out" | sed '$d' | jq "$trim")"
    message="$(sed -n '/^MESSAGE: /,$p' <<<"$out" | sed '1s/^MESSAGE: //')"
    echo
    echo "**${label}**: ${desc} ([\`${fixture}.yaml\`](../../../../test/fixtures/$step/$fixture.yaml)). Step status: \`${status}\`."
    echo
    echo '```json'
    echo "$json"
    echo '```'
    if [ "$status" != "Succeeded" ] && [ -n "$message" ]; then
      echo
      echo "The promotion stops with this message:"
      echo
      echo '```text'
      head -c 2000 <<<"$message"; echo
      echo '```'
    fi
  done
  echo "<!-- example-output:end -->"
}

update_readme() { # update_readme <step>: replace or insert the section
  local step="$1" readme tmp
  readme="$(ls kargo/custom-steps/*/"$step"/README.md)"
  tmp="$(mktemp)"; section "$step" > "$tmp"
  SECTION="$tmp" perl -0pi -e '
    my $new = do { local $/; open my $f, "<", $ENV{SECTION} or die; <$f> };
    if (/<!-- example-output:start.*?<!-- example-output:end -->\n/s) {
      s/<!-- example-output:start.*?<!-- example-output:end -->\n/$new/s;
    } elsif (/\n## Try it\n/) {
      s/\n## Try it\n/\n$new\n## Try it\n/;
    } elsif (/\n## Notes\n/) {
      s/\n## Notes\n/\n$new\n## Notes\n/;
    } else {
      $_ .= "\n$new";
    }' "$readme"
  rm -f "$tmp"
  echo "updated $readme"
}

steps=("$@")
[ ${#steps[@]} -gt 0 ] || steps=("${!runs[@]}")
for step in "${steps[@]}"; do
  [ -n "${runs[$step]:-}" ] || { echo "example-outputs.sh: no examples configured for $step" >&2; exit 1; }
  if [ "$step" = flyway-migrate ]; then test/fixtures/flyway-migrate/test-db.sh; fi
  if [ "$step" = cluster-version ]; then test/fixtures/cluster-version/fake-api.sh; fi
  update_readme "$step"
  if [ "$step" = flyway-migrate ]; then test/fixtures/flyway-migrate/test-db.sh down; fi
  if [ "$step" = cluster-version ]; then test/fixtures/cluster-version/fake-api.sh down; fi
done
